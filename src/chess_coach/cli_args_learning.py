"""Arguments for learning commands."""


def configure(sub):
    validate = sub.add_parser("validate-evidence")
    validate.add_argument("evidence_id", type=int)
    validate.add_argument("--actor", required=True)
    listing = sub.add_parser("list-evidence", help="List evidence and review states")
    listing.add_argument("--after-id", type=int, default=0)
    listing.add_argument("--limit", type=int, default=100)
    inspect = sub.add_parser("inspect-evidence", help="Inspect evidence, facts, and review history")
    inspect.add_argument("evidence_id", type=int)
    review = sub.add_parser("review-evidence", help="Record an evidence review decision")
    review.add_argument("evidence_id", type=int)
    review.add_argument("--decision", choices=["accept", "reject", "revoke"], required=True)
    review.add_argument("--actor", required=True)
    review.add_argument("--rationale")
    mastery_update = sub.add_parser("update-mastery")
    mastery_update.add_argument("skill")
    mastery_update.add_argument("operation")
    mastery_update.add_argument("--subject", default="default")
    mastery_report_parser = sub.add_parser("mastery-report")
    mastery_report_parser.add_argument("--subject", default="default")
    training_create = sub.add_parser("create-training")
    training_create.add_argument("source_type", choices=["game", "puzzle", "canonical"])
    training_create.add_argument("source_ref")
    training_create.add_argument("skill")
    training_create.add_argument("operation")
    puzzle_training = sub.add_parser(
        "create-puzzle-training", help="Create a versioned puzzle training item"
    )
    puzzle_training.add_argument("version")
    puzzle_training.add_argument("puzzle_id")
    puzzle_training.add_argument("skill")
    puzzle_training.add_argument("operation")
    training_due = sub.add_parser("due-training")
    training_due.add_argument("--limit", type=int, default=100)
    training_review = sub.add_parser("review-training")
    training_review.add_argument("item_id", type=int)
    training_review.add_argument("rating", choices=["again", "hard", "good", "easy"])
    training_review.add_argument("--elapsed-seconds", type=int)
    sub.add_parser("evidence-report")
    plan = sub.add_parser("daily-plan", help="Plan a bounded verified practice session")
    plan.add_argument("version")
    plan.add_argument("--subject", required=True)
    plan.add_argument("--limit", type=int, default=10)
    plan.add_argument("--scan-limit", type=int, default=200)
    start = sub.add_parser("start-puzzle", help="Start or resume a versioned puzzle attempt")
    start.add_argument("version")
    start.add_argument("puzzle_id")
    start.add_argument("attempt_id")
    show = sub.add_parser("show-puzzle", help="Show the current position for an attempt")
    show.add_argument("attempt_id")
    show.add_argument("--training-item-id", type=int)
    play = sub.add_parser("play-puzzle", help="Submit a UCI move")
    play.add_argument("attempt_id")
    play.add_argument("move")
    play.add_argument("--event-id", required=True)
    play.add_argument("--training-item-id", type=int)
    play.add_argument("--subject")
    hint = sub.add_parser("hint-puzzle", help="Ask for the starting square of the next move")
    hint.add_argument("attempt_id")
    hint.add_argument("--event-id", required=True)
