"""Static source and answer reservations for one pin verification."""

ROOT_MOVES = 64
COUNTERFACTUAL_ROOTS = 16
SOURCE_OBSERVERS = 1
SOURCE_PROOFS = SOURCE_OBSERVERS * (1 + COUNTERFACTUAL_ROOTS) * 16
ANSWER_PROOFS = 16
SOURCE_CAPTURE_PROBES = SOURCE_OBSERVERS * (1 + 2 * ROOT_MOVES)
ANSWER_CAPTURE_PROBES = ROOT_MOVES + 1
PROOF_LIMIT = 2 * SOURCE_PROOFS + ANSWER_PROOFS
CAPTURE_LIMIT = 2 * SOURCE_CAPTURE_PROBES + ANSWER_CAPTURE_PROBES
