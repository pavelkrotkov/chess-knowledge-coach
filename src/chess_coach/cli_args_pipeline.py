"""Arguments for bounded background-compatible processing."""

from .opening_snapshot import SOURCE, VERSION


def configure(sub):
    parser = sub.add_parser("process-pipeline", help="Synchronize and process bounded pending work")
    parser.add_argument("username", nargs="?")
    parser.add_argument("--max-games", type=int, default=25)
    parser.add_argument("--max-scan", type=int, default=1000)
    parser.add_argument("--max-positions", type=int, default=300)
    parser.add_argument("--nodes", type=int, default=10000)
    parser.add_argument("--seconds-per-position", type=float, default=1.0)
    parser.add_argument("--threads", type=int, default=1)
    parser.add_argument("--hash-mb", type=int, default=64)
    parser.add_argument("--engine-path", default="/usr/games/stockfish")
    parser.add_argument("--page-size", type=int, default=100)
    parser.add_argument("--network-retries", type=int, default=1)
    parser.add_argument("--network-requests", type=int, default=50)
    parser.add_argument("--network-timeout", type=float, default=30.0)
    parser.add_argument("--network-seconds", type=float, default=120.0)
    parser.add_argument("--network-bytes", type=int, default=8388608)
    parser.add_argument("--network-sleep", type=float, default=60.0)
    parser.add_argument("--opening-version", default=VERSION)
    parser.add_argument("--opening-source", default=SOURCE)
    parser.add_argument("--structure-version", default="0.1.0")
    parser.add_argument("--classifier-version", default="1.1.0")
    parser.add_argument("--ontology-version", default="tactical-mate-v1")
    parser.add_argument("--tactical-version", default="1.0.0")
    parser.add_argument("--no-deep", dest="deep_enabled", action="store_false")
    parser.add_argument("--deep-max-scan", type=int, default=100)
    parser.add_argument("--deep-max-games", type=int, default=4)
    parser.add_argument("--deep-per-game", type=int, default=4)
    parser.add_argument("--deep-max-jobs", type=int, default=4)
    parser.add_argument("--deep-nodes", type=int, default=50000)
    parser.add_argument("--deep-seconds", type=float, default=2.0)
    parser.add_argument("--deep-multipv", type=int, default=3)
    parser.add_argument("--no-mate", dest="mate_enabled", action="store_false")
    parser.add_argument("--mate-max-scan", type=int, default=200)
    parser.add_argument("--mate-max-decisions", type=int, default=50)
    parser.add_argument("--no-material", dest="material_enabled", action="store_false")
    parser.add_argument("--material-max-scan", type=int, default=200)
    parser.add_argument("--material-max-decisions", type=int, default=50)

    parser.add_argument("--no-pawn", dest="pawn_enabled", action="store_false")
    parser.add_argument("--pawn-max-scan", type=int, default=40)
    parser.add_argument("--pawn-max-decisions", type=int, default=4)

    sub.add_parser("pipeline-status", help="Read durable processing status")
